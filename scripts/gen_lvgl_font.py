#!/usr/bin/env python3
"""
Tiny LVGL v8 font generator (no lv_font_conv / npm needed).

Renders the requested characters from a TTF/OTF with Pillow and writes an
LVGL 8.x "fmt_txt" font (.c) using 4 bpp, uncompressed bitmaps.

Digits are forced to a common (tabular) advance width so numbers like the
speed readout don't jitter left/right as they change.

Usage:
    python3 gen_lvgl_font.py FONT.otf SIZE NAME "CHARS" OUT.c [WEIGHT] [XSCALE]

    WEIGHT  optional weight for variable fonts (e.g. 450)
    XSCALE  optional horizontal squeeze, e.g. 0.9 = 10% narrower
Example:
    python3 gen_lvgl_font.py InterDisplay-SemiBold.otf 64 ui_font_dial_64 "0123456789" ui_font_dial_64.c
"""
import sys
from PIL import Image, ImageDraw, ImageFont

BPP = 4


def main():
    if len(sys.argv) not in (6, 7, 8):
        print(__doc__)
        sys.exit(1)
    font_path, size, name, chars, out = sys.argv[1], int(sys.argv[2]), sys.argv[3], sys.argv[4], sys.argv[5]
    weight = float(sys.argv[6]) if len(sys.argv) > 6 else None
    xscale = float(sys.argv[7]) if len(sys.argv) > 7 else 1.0
    font = ImageFont.truetype(font_path, size)
    if weight is not None:
        font.set_variation_by_axes([weight])
    ascent, descent = font.getmetrics()

    chars = sorted(set(chars), key=ord)
    digits = [c for c in chars if c.isdigit()]
    digit_adv = max((font.getlength(c) for c in digits), default=0) * xscale

    bitmap = []
    glyphs = []  # (bitmap_index, adv_w, box_w, box_h, ofs_x, ofs_y, char)
    for ch in chars:
        adv = font.getlength(ch) * xscale
        shift = 0
        if ch.isdigit():
            shift = round((digit_adv - adv) / 2)
            adv = digit_adv
        if ch == " ":
            glyphs.append((len(bitmap), round(adv * 16), 0, 0, 0, 0, ch))
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = x1 - x0, y1 - y0
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        if xscale != 1.0:
            nw = max(1, round(w * xscale))
            img = img.resize((nw, h), Image.LANCZOS)
            x0 = round(x0 * xscale)
            w = nw
        px = img.load()
        start = len(bitmap)
        acc, nbits = 0, 0
        for y in range(h):
            for x in range(w):
                acc = (acc << BPP) | (px[x, y] >> (8 - BPP))
                nbits += BPP
                if nbits == 8:
                    bitmap.append(acc)
                    acc, nbits = 0, 0
        if nbits:
            bitmap.append(acc << (8 - nbits))
        glyphs.append((start, round(adv * 16), w, h, x0 + shift, -y1, ch))

    first = ord(chars[0])
    last = ord(chars[-1])
    offsets = [ord(c) - first for c in chars]

    with open(out, "w") as f:
        f.write(f"""/*******************************************************************************
 * Size: {size} px
 * Bpp: {BPP}
 * Font: {font_path.split('/')[-1]}  (SIL Open Font License)
 * Chars: {''.join(chars)!r}
 * Generated by scripts/gen_lvgl_font.py
 ******************************************************************************/

#ifdef __has_include
    #if __has_include("lvgl.h")
        #ifndef LV_LVGL_H_INCLUDE_SIMPLE
            #define LV_LVGL_H_INCLUDE_SIMPLE
        #endif
    #endif
#endif

#ifdef LV_LVGL_H_INCLUDE_SIMPLE
#include "lvgl.h"
#else
#include "lvgl/lvgl.h"
#endif

#ifndef {name.upper()}
#define {name.upper()} 1
#endif

#if {name.upper()}

static LV_ATTRIBUTE_LARGE_CONST const uint8_t glyph_bitmap[] = {{
""")
        for i in range(0, len(bitmap), 24):
            f.write("    " + ", ".join(f"0x{b:02x}" for b in bitmap[i:i + 24]) + ",\n")
        f.write("};\n\nstatic const lv_font_fmt_txt_glyph_dsc_t glyph_dsc[] = {\n")
        f.write("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0} /* id = 0 reserved */,\n")
        for (bi, adv, w, h, ox, oy, ch) in glyphs:
            f.write(f"    {{.bitmap_index = {bi}, .adv_w = {adv}, .box_w = {w}, .box_h = {h}, .ofs_x = {ox}, .ofs_y = {oy}}}, /* {ch!r} */\n")
        f.write("};\n\nstatic const uint16_t unicode_list_0[] = {\n    ")
        f.write(", ".join(f"0x{o:x}" for o in offsets))
        f.write(f"""
}};

static const lv_font_fmt_txt_cmap_t cmaps[] = {{
    {{
        .range_start = {first}, .range_length = {last - first + 1}, .glyph_id_start = 1,
        .unicode_list = unicode_list_0, .glyph_id_ofs_list = NULL, .list_length = {len(chars)},
        .type = LV_FONT_FMT_TXT_CMAP_SPARSE_TINY
    }}
}};

#if LV_VERSION_CHECK(8, 0, 0)
static lv_font_fmt_txt_glyph_cache_t cache;
static const lv_font_fmt_txt_dsc_t font_dsc = {{
#else
static lv_font_fmt_txt_dsc_t font_dsc = {{
#endif
    .glyph_bitmap = glyph_bitmap,
    .glyph_dsc = glyph_dsc,
    .cmaps = cmaps,
    .kern_dsc = NULL,
    .kern_scale = 0,
    .cmap_num = 1,
    .bpp = {BPP},
    .kern_classes = 0,
    .bitmap_format = 0,
#if LV_VERSION_CHECK(8, 0, 0)
    .cache = &cache
#endif
}};

#if LV_VERSION_CHECK(8, 0, 0)
const lv_font_t {name} = {{
#else
lv_font_t {name} = {{
#endif
    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,
    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,
    .line_height = {ascent + descent},
    .base_line = {descent},
#if !(LVGL_VERSION_MAJOR == 6 && LVGL_VERSION_MINOR == 0)
    .subpx = LV_FONT_SUBPX_NONE,
#endif
#if LV_VERSION_CHECK(7, 4, 0) || LVGL_VERSION_MAJOR >= 8
    .underline_position = 0,
    .underline_thickness = 0,
#endif
    .dsc = &font_dsc
}};

#endif /* {name.upper()} */
""")
    print(f"{out}: {len(chars)} glyphs, {len(bitmap)} bytes")


if __name__ == "__main__":
    main()
